/**
 * Generate the package dependency diagram FROM THE CODE and write it into the
 * docs. Never edit the output by hand — `npm run graph:verify` regenerates it and
 * fails if the committed file differs, so a stale diagram is a red build rather
 * than something someone notices months later.
 *
 *   npm run graph          → write docs-site/docs/architecture/package-graph.md
 *   npm run graph:verify   → fail if that file is out of date
 *   npm run graph:check    → enforce the ARCHITECTURE RULES (.dependency-cruiser.cjs)
 *
 * The picture is the by-product; `graph:check` is the part that keeps the
 * architecture honest.
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = resolve(ROOT, 'docs-site/docs/architecture/package-graph.md');
const CHECK = process.argv.includes('--check');

// Ask dependency-cruiser for the raw graph, then reduce it to package→package
// edges. Its own reporters draw MODULES; at this level the useful picture is one
// node per package.
const json = JSON.parse(
    execFileSync(
        'npx',
        [
            'depcruise',
            'packages',
            '--config',
            '.dependency-cruiser.cjs',
            '--output-type',
            'json',
        ],
        { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 }
    )
);

// A directory under packages/ counts as a package only if it HAS a package.json —
// `packages/` also holds loose build scripts (browser-tsup.mjs), and a path regex
// alone would draw those as nodes.
const isPackageDir = dir => {
    try {
        readFileSync(resolve(ROOT, dir, 'package.json'));
        return true;
    } catch {
        return false;
    }
};
const packageCache = new Map();
const packageOf = path => {
    const m = /^packages\/(examples\/[^/]+|[^/]+)/.exec(path);
    if (!m) return null;
    const dir = `packages/${m[1]}`;
    if (!packageCache.has(dir)) packageCache.set(dir, isPackageDir(dir));
    return packageCache.get(dir) ? m[1] : null;
};
const externalExodra = path => {
    const m = /node_modules\/(@exodra\/[^/]+)/.exec(path);
    return m ? m[1] : null;
};

// name → set of names it depends on
const edges = new Map();
for (const mod of json.modules) {
    const from = packageOf(mod.source);
    if (!from) continue;
    for (const dep of mod.dependencies ?? []) {
        const to = externalExodra(dep.resolved) ?? packageOf(dep.resolved);
        if (!to) continue;
        const target = to.startsWith('@exodra/') ? to.slice('@exodra/'.length) : to;
        if (target === from) continue;
        if (!edges.has(from)) edges.set(from, new Set());
        edges.get(from).add(target);
    }
}

const lines = ['graph TD'];
for (const from of [...edges.keys()].sort()) {
    for (const to of [...edges.get(from)].sort()) {
        lines.push(`    ${from.replace(/[^\w]/g, '_')} --> ${to.replace(/[^\w]/g, '_')}`);
    }
}

const page = `---
title: Package graph
---

{/* GENERATED by \`npm run graph\` — do not edit. \`npm run graph:verify\` fails on drift. */}

# Package graph

Every edge below is a real \`import\` found in the sources, not a drawing: the
diagram is regenerated from the code and verified in CI.

The rules these packages must obey (core stays zero-dependency, the two renderers
never reference each other, build-time tooling never reaches the runtime) are
enforced separately by \`npm run graph:check\`.

\`\`\`mermaid
${lines.join('\n')}
\`\`\`
`;

if (CHECK) {
    let current = '';
    try {
        current = readFileSync(OUT, 'utf8');
    } catch {
        /* missing counts as out of date */
    }
    if (current !== page) {
        console.error(
            `${OUT} is out of date.\nRun \`npm run graph\` and commit the result.`
        );
        process.exit(1);
    }
    console.log('package graph is up to date');
} else {
    mkdirSync(dirname(OUT), { recursive: true });
    writeFileSync(OUT, page);
    console.log(`wrote ${OUT} (${lines.length - 1} edges)`);
}
